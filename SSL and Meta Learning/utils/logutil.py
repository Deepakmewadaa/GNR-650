"""Tiny logging helpers: stdout + file tee, CSV metrics logger, experiment-log appender."""
import csv
import datetime
import json
import os
import sys


class Tee:
    """Duplicate stdout/stderr into a log file (append mode, survives resume)."""

    def __init__(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        self.f = open(path, "a", buffering=1)
        self.stdout, self.stderr = sys.stdout, sys.stderr
        sys.stdout, sys.stderr = self, self
        self.f.write(f"\n===== {now()} : {' '.join(sys.argv)}\n")

    def write(self, s):
        self.stdout.write(s)
        try:
            self.f.write(s)
        except ValueError:
            pass

    def flush(self):
        self.stdout.flush()
        try:
            self.f.flush()
        except ValueError:
            pass

    def isatty(self):
        return False

    def close(self):
        sys.stdout, sys.stderr = self.stdout, self.stderr
        self.f.close()


def now():
    return datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")


class CSVLogger:
    def __init__(self, path):
        self.path = path
        os.makedirs(os.path.dirname(path), exist_ok=True)

    def log(self, row: dict):
        exists = os.path.isfile(self.path)
        if exists:
            with open(self.path) as f:
                header = next(csv.reader(f), None)
            if header and set(row) - set(header):   # new columns -> rewrite with union header
                with open(self.path) as f:
                    rows = list(csv.DictReader(f))
                header = header + [k for k in row if k not in header]
                with open(self.path, "w", newline="") as f:
                    w = csv.DictWriter(f, fieldnames=header)
                    w.writeheader()
                    w.writerows(rows)
        else:
            header = list(row)
        with open(self.path, "a", newline="") as f:
            w = csv.DictWriter(f, fieldnames=header, extrasaction="ignore")
            if not exists:
                w.writeheader()
            w.writerow(row)


def save_json(obj, path):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(obj, f, indent=2, default=_json_default)
    os.replace(tmp, path)


def _json_default(o):
    try:
        import numpy as np
        if isinstance(o, np.generic):
            return o.item()
        if isinstance(o, np.ndarray):
            return o.tolist()
    except ImportError:
        pass
    try:
        import torch
        if isinstance(o, torch.Tensor):
            return o.tolist()
    except ImportError:
        pass
    return str(o)


def load_json(path, default=None):
    if not os.path.isfile(path):
        return default
    with open(path) as f:
        return json.load(f)


def append_experiment_log(path, title, config: dict, metrics: dict, status="OK", notes=""):
    """Append one entry to docs/experiment_log.md. Called automatically by training scripts and
    ablations, including failed / underperforming runs, so the report never relies on memory."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    new = not os.path.isfile(path)
    with open(path, "a") as f:
        if new:
            f.write("# Experiment log\n\nAuto-generated by the training/ablation scripts. Every run is "
                    "appended here (including failed or underperforming runs). Numbers are copied from "
                    "real runs only.\n\n")
        f.write(f"## {now()} — {title} — **{status}**\n\n")
        if notes:
            f.write(f"{notes}\n\n")
        f.write("Metrics:\n\n```json\n" + json.dumps(metrics, indent=1, default=_json_default) + "\n```\n\n")
        f.write("<details><summary>config</summary>\n\n```json\n"
                + json.dumps(config, indent=1, sort_keys=True, default=_json_default) + "\n```\n</details>\n\n")
